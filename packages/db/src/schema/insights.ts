/**
 * Contributing factors that influence the sentiment score
 */
export interface SentimentFactor {
  name: string; // e.g., "Price Volatility", "Social Hype", "Sales Volume"
  weight: number; // How much this factor contributes (0-1)
  value: number; // The factor's current value (0-100)
  trend: 'rising' | 'falling' | 'stable';
  description?: string; // Human-readable explanation
}

/**
 * Sentiment Snapshots table
 *
 * Tracks the "Fear & Greed" index of the market over time.
 * Enables historical trend analysis and market timing insights.
 *
 * Score interpretation:
 * - 0-20: Extreme Fear (buying opportunity?)
 * - 21-40: Fear
 * - 41-60: Neutral
 * - 61-80: Greed
 * - 81-100: Extreme Greed (bubble territory?)
 */
export const sentimentSnapshots = pgTable(
  'sentiment_snapshots',
  {
    id: uuid('id').defaultRandom().primaryKey(),

    // Which market this sentiment applies to
    game: tcgGameEnum('game').notNull().default('pokemon'),

    // The headline number: 0-100 score
    score: integer('score').notNull(),

    // Human-readable label derived from score
    label: sentimentLabelEnum('label').notNull(),

    // Directional change from previous snapshot
    previousScore: integer('previous_score'),
    scoreChange: integer('score_change'), // Can be negative

    // Contributing factors with weighted breakdown
    // Enables "Why is the market fearful?" explanations
    factors: jsonb('factors').$type<SentimentFactor[]>().default([]),

    // Optional AI-generated narrative explaining the sentiment
    narrative: text('narrative'),

    // Data sources used to calculate this snapshot
    dataSources: jsonb('data_sources').$type<string[]>().default([]),

    // Sample size / confidence
    sampleSize: integer('sample_size'), // Number of data points analyzed
    confidenceScore: integer('confidence_score'), // 0-100 confidence in the score

    // Timestamps
    recordedAt: timestamp('recorded_at', { withTimezone: true }).defaultNow().notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => ({
    // Historical queries: "Get Pokemon sentiment over time"
    gameTimeIdx: index('idx_sentiment_game_time').on(table.game, table.recordedAt),

    // Dashboard: "Get latest sentiment for each game"
    recordedIdx: index('idx_sentiment_recorded').on(table.recordedAt),

    // Analysis: "Find all extreme fear/greed moments"
    labelIdx: index('idx_sentiment_label').on(table.label),

    // Game-specific queries
    gameIdx: index('idx_sentiment_game').on(table.game),
  }),
);

