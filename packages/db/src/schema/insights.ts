/**
 * Citation structure for Perplexity-style footnotes
 */
export interface MarketReportCitation {
  id: string; // Unique citation ID (e.g., "cite-1")
  source: string; // Source name (e.g., "TCGPlayer", "Reddit r/pkmntcg")
  url?: string; // Optional URL to source
  quote?: string; // Relevant quote from source
  relevance: number; // 0-1 score of how relevant this citation is
  accessedAt: string; // ISO timestamp when source was accessed
}

/**
 * AI metadata for tracking model performance and costs
 */
export interface MarketReportAIMetadata {
  modelId: string; // e.g., "gpt-4o", "claude-3-5-sonnet"
  promptVersion: string; // Version of the prompt template used
  tokensInput: number;
  tokensOutput: number;
  totalTokens: number;
  latencyMs: number; // Time to generate in milliseconds
  temperature: number; // Model temperature used
  ragSourceCount: number; // Number of RAG sources retrieved
}

/**
 * Market Reports table
 *
 * Stores AI-generated analysis to be served instantly to Pro users.
 * Caches expensive LLM computations to avoid per-request generation costs.
 *
 * Query patterns:
 * - Latest reports by game and type (Dashboard)
 * - Published reports feed (Blog/Content page)
 * - Historical reports for trend analysis
 */
export const marketReports = pgTable(
  'market_reports',
  {
    id: uuid('id').defaultRandom().primaryKey(),

    // Core content
    title: text('title').notNull(),
    slug: text('slug').notNull().unique(), // URL-safe identifier for the report

    // Report classification
    reportType: reportTypeEnum('report_type').notNull(),
    game: tcgGameEnum('game').notNull().default('pokemon'),

    // Rich content (Markdown) generated by the LLM
    content: text('content').notNull(),

    // Executive summary for preview cards (max 280 chars)
    summary: text('summary'),

    // Structured citations for the "Perplexity style" UI
    // Enables interactive footnotes in the frontend
    citations: jsonb('citations').$type<MarketReportCitation[]>().default([]),

    // Key takeaways (bullet points for quick scanning)
    keyTakeaways: jsonb('key_takeaways').$type<string[]>().default([]),

    // Featured cards mentioned in the report (for quick-links)
    featuredCardIds: jsonb('featured_card_ids').$type<string[]>().default([]),

    // AI metadata for debugging/refining prompts and cost tracking
    aiMetadata: jsonb('ai_metadata').$type<MarketReportAIMetadata>(),

    // SEO and engagement
    viewCount: integer('view_count').default(0).notNull(),
    shareCount: integer('share_count').default(0).notNull(),

    // Visibility control
    isPublished: text('is_published', { enum: ['draft', 'published', 'archived'] })
      .default('draft')
      .notNull(),

    // Lifecycle timestamps
    publishedAt: timestamp('published_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),

    // TTL for cache invalidation (when should this report be regenerated?)
    expiresAt: timestamp('expires_at', { withTimezone: true }),
  },
  (table) => ({
    // Fast lookup for dashboard: "Get latest Pokemon daily snapshot"
    gameTypeIdx: index('idx_market_reports_game_type').on(table.game, table.reportType),

    // Feed queries: "Get all published reports, newest first"
    publishedIdx: index('idx_market_reports_published').on(
      table.isPublished,
      table.publishedAt,
    ),

    // Slug lookup for direct URL access
    slugIdx: index('idx_market_reports_slug').on(table.slug),

    // Cache invalidation: "Find expired reports needing refresh"
    expiresIdx: index('idx_market_reports_expires').on(table.expiresAt),

    // Content discovery by type
    typeIdx: index('idx_market_reports_type').on(table.reportType),
  }),
);

